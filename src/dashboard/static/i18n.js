  /* ── Core engine ──────────────────────────────────────────────────────── */

  function getLang() {
    return localStorage.getItem('ap_lang') || 'en';
  }

  function translate(lang) {
    var dict = T[lang] || T['en'];
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (dict[k] !== undefined) el.textContent = dict[k];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-html');
      if (dict[k] !== undefined) el.innerHTML = dict[k];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-ph');
      if (dict[k] !== undefined) el.placeholder = dict[k];
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-title');
      if (dict[k] !== undefined) el.title = dict[k];
    });
    document.documentElement.lang = lang;
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      var active = btn.getAttribute('data-lang') === lang;
      btn.style.opacity     = active ? '1'   : '0.4';
      btn.style.fontWeight  = active ? '700' : '400';
      btn.style.borderColor = active ? '#22c55e' : '#1a3d26';
    });
  }

  /* ── Public API ───────────────────────────────────────────────────────── */

  window.setLang = function (lang) {
    if (!T[lang]) return;
    localStorage.setItem('ap_lang', lang);
    translate(lang);
    fetch('/api/set-language', {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: 'lang=' + encodeURIComponent(lang)
    }).catch(function () {});
  };

  window.AP_T = function (key) {
    return (T[getLang()] || T['en'])[key] || key;
  };

  document.addEventListener('DOMContentLoaded', function () {
    translate(getLang());
  });

